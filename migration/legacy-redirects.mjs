import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MAP_PATH = join(PROJECT_ROOT, 'migration', 'legacy-url-map.csv');
const REDIRECTS_PATH = join(PROJECT_ROOT, 'public', '_redirects');
const HTACCESS_PATH = join(PROJECT_ROOT, '.htaccess');
const NGINX_PATH = join(PROJECT_ROOT, 'docs', 'nginx-legacy-redirects.conf');
const CUTOVER_PATH = join(PROJECT_ROOT, 'docs', 'PRODUCTION_CUTOVER.md');
const ALLOWED_STATUSES = new Set(['200', '301', '301 + fallback']);

export const CUTOVER_TABLE_START = '<!-- LEGACY_REDIRECTS:START -->';
export const CUTOVER_TABLE_END = '<!-- LEGACY_REDIRECTS:END -->';

function parseCsv(text) {
  const rows = [];
  let field = '';
  let row = [];
  let quoted = false;

  const pushRow = () => {
    row.push(field);
    if (row.some((value) => value !== '')) rows.push(row);
    field = '';
    row = [];
  };

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (character === '"') {
      if (quoted && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === ',' && !quoted) {
      row.push(field);
      field = '';
    } else if ((character === '\n' || character === '\r') && !quoted) {
      if (character === '\r' && text[index + 1] === '\n') index += 1;
      pushRow();
    } else {
      field += character;
    }
  }

  if (quoted) throw new Error('legacy URL map contains an unterminated quoted CSV field');
  if (field || row.length > 0) pushRow();
  return rows;
}

function normalizePath(value, column, rowNumber) {
  const path = value.trim();
  if (!path.startsWith('/') || path.startsWith('//') || /[?#\\\s]/.test(path)) {
    throw new Error(`legacy URL map row ${rowNumber}: ${column} must be a root-relative path`);
  }
  if (path.length > 1 && path.endsWith('/')) {
    throw new Error(`legacy URL map row ${rowNumber}: ${column} must not end with a slash`);
  }
  return path;
}

function compareBySource(first, second) {
  return first.source < second.source ? -1 : first.source > second.source ? 1 : 0;
}

function quoteMarkdown(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', '<br>');
}

function escapeRegularExpression(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function sortedRedirectEntries(entries) {
  return [...entries].filter(isRedirect).sort(compareBySource);
}

export function isRedirect(entry) {
  return entry.status.startsWith('301');
}

export function isStaticFallback(entry) {
  return entry.status === '301 + fallback';
}

export function canonicalTargetPath(target) {
  return target === '/' ? '/' : `${target}/`;
}

export async function loadLegacyUrlMap(mapPath = MAP_PATH) {
  const rows = parseCsv(await readFile(mapPath, 'utf8'));
  const [header, ...dataRows] = rows;
  const expectedHeader = ['source', 'target', 'status', 'reason'];
  if (!header || header.length !== expectedHeader.length || header.some((value, index) => value !== expectedHeader[index])) {
    throw new Error(`legacy URL map must start with ${expectedHeader.join(',')}`);
  }

  const sources = new Set();
  const entries = dataRows.map((row, index) => {
    const rowNumber = index + 2;
    if (row.length !== expectedHeader.length) {
      throw new Error(`legacy URL map row ${rowNumber}: expected ${expectedHeader.length} columns, got ${row.length}`);
    }

    const source = normalizePath(row[0], 'source', rowNumber);
    const target = normalizePath(row[1], 'target', rowNumber);
    const status = row[2].trim();
    const reason = row[3].trim();
    if (!ALLOWED_STATUSES.has(status)) {
      throw new Error(`legacy URL map row ${rowNumber}: unsupported status ${status}`);
    }
    if (!reason) throw new Error(`legacy URL map row ${rowNumber}: reason is required`);
    if (sources.has(source)) throw new Error(`legacy URL map row ${rowNumber}: duplicate source ${source}`);
    if (isRedirect({ status }) && source === target) {
      throw new Error(`legacy URL map row ${rowNumber}: redirects must not target themselves`);
    }
    if (status === '200' && source !== target) {
      throw new Error(`legacy URL map row ${rowNumber}: status 200 must retain the same canonical path`);
    }
    sources.add(source);
    return { source, target, status, reason };
  });

  return entries.sort(compareBySource);
}

export function renderRedirects(entries) {
  const redirects = sortedRedirectEntries(entries)
    .map(({ source, target }) => `${source} ${canonicalTargetPath(target)} 301`);

  return [
    '# Generated by `node migration/build_legacy_redirects.mjs`. Do not edit.',
    '# Source: migration/legacy-url-map.csv',
    ...redirects,
    '',
  ].join('\n');
}

/**
 * Apache .htaccess variant. RewriteRule patterns are relative to the deployment
 * directory, so the leading slash is intentionally removed before escaping.
 */
export function renderHtaccess(entries) {
  const rules = sortedRedirectEntries(entries).map(({ source, target }) => {
    const relativeSource = source === '/' ? '' : source.slice(1);
    return `RewriteRule ^${escapeRegularExpression(relativeSource)}$ ${canonicalTargetPath(target)} [R=301,L]`;
  });

  return [
    '# Generated by `node migration/build_legacy_redirects.mjs`. Do not edit.',
    '# Source: migration/legacy-url-map.csv',
    '# Requires Apache mod_rewrite and AllowOverride FileInfo.',
    'RewriteEngine On',
    ...rules,
    '',
  ].join('\n');
}

/**
 * nginx variant for inclusion inside a server block. Exact locations keep a
 * legacy prefix from accidentally redirecting a different published route.
 */
export function renderNginxRedirects(entries) {
  const locations = sortedRedirectEntries(entries).map(({ source, target }) => (
    `location = ${source} { return 301 ${canonicalTargetPath(target)}$is_args$args; }`
  ));

  return [
    '# Generated by `node migration/build_legacy_redirects.mjs`. Do not edit.',
    '# Source: migration/legacy-url-map.csv',
    '# Include this file inside the relevant `server { ... }` block.',
    '# Query strings are retained so campaign tags survive the migration redirect.',
    ...locations,
    '',
  ].join('\n');
}

export function renderCutoverTable(entries) {
  return [
    '| Source | Target | Status | Reason |',
    '| --- | --- | --- | --- |',
    ...[...entries]
      .sort(compareBySource)
      .map(({ source, target, status, reason }) => (
        `| \`${quoteMarkdown(source)}\` | \`${quoteMarkdown(canonicalTargetPath(target))}\` | ${quoteMarkdown(status)} | ${quoteMarkdown(reason)} |`
      )),
  ].join('\n');
}

export function replaceCutoverTable(document, entries) {
  const start = document.indexOf(CUTOVER_TABLE_START);
  const end = document.indexOf(CUTOVER_TABLE_END);
  if (start < 0 || end < 0 || end <= start) {
    throw new Error('PRODUCTION_CUTOVER.md is missing the legacy redirect table markers');
  }

  return `${document.slice(0, start + CUTOVER_TABLE_START.length)}\n${renderCutoverTable(entries)}\n${document.slice(end)}`;
}

async function writeIfChanged(filePath, content) {
  let current = '';
  try {
    current = await readFile(filePath, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current !== content) await writeFile(filePath, content);
  return current !== content;
}

export async function buildLegacyRedirectArtifacts({ check = false } = {}) {
  const entries = await loadLegacyUrlMap();
  const redirects = renderRedirects(entries);
  const htaccess = renderHtaccess(entries);
  const nginx = renderNginxRedirects(entries);
  const cutover = replaceCutoverTable(await readFile(CUTOVER_PATH, 'utf8'), entries);
  const expected = [
    [REDIRECTS_PATH, redirects],
    [HTACCESS_PATH, htaccess],
    [NGINX_PATH, nginx],
    [CUTOVER_PATH, cutover],
  ];

  if (check) {
    const stale = [];
    for (const [filePath, content] of expected) {
      try {
        if (await readFile(filePath, 'utf8') !== content) stale.push(filePath);
      } catch (error) {
        if (error.code === 'ENOENT') stale.push(filePath);
        else throw error;
      }
    }
    return { entries, stale };
  }

  const changed = [];
  for (const [filePath, content] of expected) {
    if (await writeIfChanged(filePath, content)) changed.push(filePath);
  }
  return { entries, changed };
}
